import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { beforeEach, expect, it, vi } from "vitest";
import { apiRequest } from "../../../lib/api-client";
import { I18nProvider } from "../i18n";
import { ServiceBooking } from "./service-booking";
vi.mock("../../../lib/api-client", async (original) => ({ ...await original<object>(), apiRequest: vi.fn() }));
beforeEach(() => { vi.clearAllMocks(); HTMLElement.prototype.scrollIntoView = vi.fn(); HTMLDialogElement.prototype.showModal = function () { this.setAttribute("open", ""); }; });
it("selects a service and time, preserves idempotency on retry and shows confirmation", async () => {
 const submissions: Record<string, unknown>[] = [];
 vi.mocked(apiRequest).mockImplementation(async (path, options) => {
  if (path.endsWith('/services')) return { services: [{ id:'yoga',name:'Йога',description:'Занятие с тренером',category_name:'Тренер Анна',duration_minutes:60,price_minor:2500,currency:'EUR' }] };
  if (path.includes('service-availability')) return { date:'2026-10-20',timezone:'Europe/Bratislava',slots:[{time:'12:00',starts_at:'2026-10-20T10:00:00Z'}] };
  submissions.push(JSON.parse(String(options?.body)));
  if(submissions.length===1) throw new Error('network');
  return {reservation:{id:'reservation',currency:'EUR',guest_count:1,preorder_total_minor:0,code:'TEST123',starts_at:'2026-10-20T10:00:00Z'}};
 });
 render(<I18nProvider initialLocale="ru"><ServiceBooking venueID="venue" /></I18nProvider>);
 fireEvent.click(await screen.findByRole('button',{name:/Йога/}));
 expect(screen.queryByLabelText('Имя')).not.toBeInTheDocument();
 fireEvent.click(screen.getByRole('button',{name:'Забронировать онлайн'}));
 fireEvent.click(await screen.findByRole('button',{name:'12:00'}));
 fireEvent.change(screen.getByLabelText('Имя'),{target:{value:'Анна'}});
 fireEvent.change(screen.getByLabelText('Телефон'),{target:{value:'+421900000000'}});
 fireEvent.click(screen.getByRole('button',{name:'Продолжить'}));
 const submit=screen.getByRole('button',{name:'Забронировать'});
 fireEvent.click(submit);
 await screen.findByRole('alert');
 fireEvent.click(submit);
 await screen.findByText('Номер брони: TEST123');
 await waitFor(()=>expect(submissions).toHaveLength(2));
 expect(submissions[0].idempotency_key).toBe(submissions[1].idempotency_key);
 expect(submissions[1]).toMatchObject({service_id:'yoga',expected_price_minor:2500});
 expect(screen.getByText('Номер брони: TEST123')).toBeInTheDocument();
});
